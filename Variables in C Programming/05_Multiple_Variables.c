#include <stdio.h>

int main() {
    int age = 21;
    float height = 5.8;
    char grade = 'A';
    double percentage = 89.5678;

    printf("Age = %d\n", age);
    printf("Height = %.2f\n", height);
    printf("Grade = %c\n", grade);
    printf("Percentage = %.4lf\n", percentage);

    return 0;
}
